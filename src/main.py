"""
Command line runner for VibeFinder.

Two ways to get recommendations:
1. Structured profile matching (original VibeFinder): recommend_songs()
2. Free-text RAG pipeline (new): recommend_with_rag() - retrieves the closest
   songs for a natural-language request, then asks an LLM to explain the
   picks, grounded only in the retrieved data. Falls back to a safe
   templated explanation if the LLM is unavailable or fails the guardrail.

Run with no arguments to see both demonstrated. Pass --query to try your
own free-text request against the RAG pipeline.
"""

import argparse

from src.recommender import load_songs, recommend_songs, recommend_with_rag

SAMPLE_QUERIES = [
    "something calm and acoustic for studying late at night",
    "high energy pop for a workout",
    "happy upbeat songs",
]


def print_structured_demo(songs) -> None:
    print("=" * 60)
    print("1) Structured profile matching (original VibeFinder)")
    print("=" * 60)
    user_prefs = {"genre": "pop", "mood": "happy", "energy": 0.8}
    recommendations = recommend_songs(user_prefs, songs, k=5)

    print(f"\nProfile: {user_prefs}")
    print("Top Recommendations")
    print("-" * 40)
    for rank, (song, score, explanation) in enumerate(recommendations, start=1):
        print(f"{rank}. {song['title']} by {song['artist']}  (Score: {score:.2f})")
        for reason in explanation.split("; "):
            print(f"     - {reason}")
        print()


def print_rag_result(songs, query: str) -> None:
    result = recommend_with_rag(query, songs, k=3)
    print(f'\nQuery: "{query}"')
    print(f"(generated by: {result['source']}, guardrail passed: {result['guardrail_passed']})")
    print("Retrieved songs:")
    for song, score in result["retrieved"]:
        print(f"  - {song['title']} by {song['artist']} (similarity: {score:.3f})")
    print(f"Explanation: {result['explanation']}")


def main() -> None:
    parser = argparse.ArgumentParser(description="VibeFinder music recommender")
    parser.add_argument(
        "--query", type=str, default=None, help="Free-text request for the RAG pipeline"
    )
    args = parser.parse_args()

    songs = load_songs("data/songs.csv")
    print(f"Loaded songs: {len(songs)}")
    print()

    print_structured_demo(songs)

    print("\n" + "=" * 60)
    print("2) Free-text RAG pipeline (retrieve -> generate -> guardrail)")
    print("=" * 60)

    if args.query:
        print_rag_result(songs, args.query)
    else:
        for query in SAMPLE_QUERIES:
            print_rag_result(songs, query)
            print("-" * 40)


if __name__ == "__main__":
    main()
